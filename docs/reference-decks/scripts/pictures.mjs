// The pictures of the reference decks as the asset records a template carries: id (the sha256
// of the file), size and dimensions. Written to packages/templates/src/builtin, because the
// samples of the built-in templates use the same pictures.
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { root } from './decks.mjs';

const target = join(root, '..', '..', 'packages', 'templates', 'src', 'builtin', 'pictures.generated.ts');

/** Width and height of a WebP file, from its first chunk. */
function webpSize(bytes) {
  const kind = bytes.toString('ascii', 12, 16);
  if (kind === 'VP8 ') return [bytes.readUInt16LE(26) & 0x3fff, bytes.readUInt16LE(28) & 0x3fff];
  if (kind === 'VP8L') {
    const bits = bytes.readUInt32LE(21);
    return [(bits & 0x3fff) + 1, ((bits >> 14) & 0x3fff) + 1];
  }
  if (kind === 'VP8X') return [bytes.readUIntLE(24, 3) + 1, bytes.readUIntLE(27, 3) + 1];
  throw new Error(`not a WebP chunk: ${kind}`);
}

export function writePictures() {
  const dir = join(root, 'images');
  const entries = readdirSync(dir)
    .filter((file) => file.endsWith('.webp'))
    .sort()
    .map((file) => {
      const bytes = readFileSync(join(dir, file));
      const id = createHash('sha256').update(bytes).digest('hex');
      const [width, height] = webpSize(bytes);
      const key = file.replace(/\.webp$/, '').replace(/-(\w)/g, (_, c) => c.toUpperCase());
      return `  ${key}: {\n    id: '${id}',\n    file: '${id}.webp',\n    mime: 'image/webp',\n    kind: 'image',\n    bytes: ${bytes.length},\n    width: ${width},\n    height: ${height},\n    origin: 'ai',\n    name: '${file}',\n  },`;
    });
  const out = `// Generated by docs/reference-decks/scripts/build.mjs. Do not edit.
import type { AssetMeta } from '@slidr/model';

/** The pictures under docs/reference-decks/images, as assets. \`name\` is the file there. */
export const pictures = {
${entries.join('\n')}
} satisfies Record<string, AssetMeta>;
`;
  let before = '';
  try {
    before = readFileSync(target, 'utf8');
  } catch {
    // First run.
  }
  if (before !== out) writeFileSync(target, out);
  return `pictures.generated.ts: ${entries.length} pictures${before === out ? ', up to date' : ', written'}`;
}
