// Builds the chart engine and the chart library into one script and writes it to
// src/chart/bundle.generated.ts, from where `@slidr/html-export` puts it in an exported file that
// has charts (WG6-T08, EXP-12, EXP-13). Run after changing anything under src/chart, or the
// version of the library:
//   pnpm --filter @slidr/renderer chart-bundle
//
// This is a Vite config run with the desktop app's Vite, as the runtime's bundle is (see
// packages/runtime/scripts/bundle.config.mjs). `src/chart/bundle.test.ts` fails when the sources
// have changed since the bundle was built.
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(root, 'src', 'chart');
const out = join(src, 'bundle.generated.ts');

// pnpm links a package next to its own dependencies: the library's renderer is its neighbour.
const libraryDir = realpathSync(join(root, 'node_modules', 'echarts'));
const manifest = (dir) => JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
const echarts = manifest(libraryDir);
const zrender = manifest(join(libraryDir, '..', 'zrender'));

/** The same hash as in src/chart/bundle.test.ts: the library's version and every source file. */
function sourceHash() {
  const hash = createHash('sha256');
  hash.update(`echarts@${echarts.version}\n`);
  const files = readdirSync(src)
    .filter((f) => f.endsWith('.ts') && !f.endsWith('.test.ts') && !f.endsWith('.generated.ts'))
    .sort();
  for (const file of files) {
    hash.update(`${file}\n${readFileSync(join(src, file), 'utf8').replace(/\r\n/g, '\n')}\n`);
  }
  return hash.digest('hex');
}

/**
 * What the licences ask a copy of the library to carry (Apache-2.0, section 4): the notice of
 * the library, and where its licence is.
 */
const banner = [
  '/*!',
  ` * Apache ECharts ${echarts.version}, Copyright 2017-2026 The Apache Software Foundation.`,
  ' * This product includes software developed at The Apache Software Foundation',
  ' * (https://www.apache.org/). Licensed under the Apache License, Version 2.0:',
  ' * https://www.apache.org/licenses/LICENSE-2.0',
  ` * ZRender ${zrender.version}, Copyright (c) 2017, Baidu Inc. BSD 3-Clause License:`,
  ' * https://github.com/ecomfe/zrender/blob/master/LICENSE',
  ' */',
].join('\n');

/** Writes the bundle as a TypeScript module instead of a file in `dist`. */
const writeModule = {
  name: 'slidr-chart-module',
  async generateBundle(_options, bundle) {
    const chunk = Object.values(bundle).find((file) => file.type === 'chunk');
    if (!chunk) throw new Error('the build produced no chunk');
    const script = `${banner}\n${chunk.code.trim()}`;
    const code = [
      '// Generated by scripts/chartBundle.config.mjs. Do not edit: run `pnpm --filter @slidr/renderer chart-bundle`.',
      '',
      '/** Hash of the sources the bundle was built from. */',
      `export const chartBundleSource = ${JSON.stringify(sourceHash())};`,
      '',
      '/** The version of the chart library in the bundle. */',
      `export const chartLibraryVersion = ${JSON.stringify(echarts.version)};`,
      '',
      '/** The chart engine and the chart library as one script that draws the charts of the document it is in. */',
      `export const chartBundle: string = ${JSON.stringify(script)};`,
      '',
    ].join('\n');
    const config = await prettier.resolveConfig(out);
    writeFileSync(out, await prettier.format(code, { ...config, filepath: out }));
    console.log(`chart bundle.generated.ts: ${(script.length / 1024).toFixed(1)} kB`);
  },
};

export default {
  root,
  publicDir: false,
  logLevel: 'warn',
  plugins: [writeModule],
  // The library keeps its development warnings behind this; a library build leaves it as it is,
  // and a browser has no `process`.
  define: { 'process.env.NODE_ENV': JSON.stringify('production') },
  build: {
    write: false,
    // Exported files should open in any current browser, not only in the app's WebView.
    target: 'es2022',
    lib: { entry: join(src, 'standalone.ts'), formats: ['iife'], name: 'SlidrCharts' },
  },
};
