// Builds the runtime into one script and writes it to src/bundle.generated.ts, from where
// `@slidr/html-export` puts it in every exported file (WG9-T10). Run after changing the runtime:
//   pnpm --filter @slidr/runtime bundle
//
// This is a Vite config run with the desktop app's Vite, the bundler the workspace already has,
// so the runtime needs no dependency of its own. `src/bundle.test.ts` fails when the sources
// have changed since the bundle was built.
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(root, 'src');
const out = join(src, 'bundle.generated.ts');

/** The same hash as in src/bundle.test.ts: every source file, by name, with LF line ends. */
function sourceHash() {
  const hash = createHash('sha256');
  const files = readdirSync(src)
    .filter((f) => f.endsWith('.ts') && !f.endsWith('.test.ts') && !f.endsWith('.generated.ts'))
    .sort();
  for (const file of files) {
    hash.update(`${file}\n${readFileSync(join(src, file), 'utf8').replace(/\r\n/g, '\n')}\n`);
  }
  return hash.digest('hex');
}

/** Writes the bundle as a TypeScript module instead of a file in `dist`. */
const writeModule = {
  name: 'slidr-runtime-module',
  async generateBundle(_options, bundle) {
    const chunk = Object.values(bundle).find((file) => file.type === 'chunk');
    if (!chunk) throw new Error('the build produced no chunk');
    const code = [
      '// Generated by scripts/bundle.config.mjs. Do not edit: run `pnpm --filter @slidr/runtime bundle`.',
      '',
      '/** Hash of the sources the bundle was built from. */',
      `export const playerBundleSource = ${JSON.stringify(sourceHash())};`,
      '',
      '/** The runtime as one script that starts the show of the document it is in. */',
      `export const playerBundle = ${JSON.stringify(chunk.code.trim())};`,
      '',
    ].join('\n');
    const config = await prettier.resolveConfig(out);
    writeFileSync(out, await prettier.format(code, { ...config, filepath: out }));
    console.log(`bundle.generated.ts: ${(chunk.code.length / 1024).toFixed(1)} kB`);
  },
};

export default {
  root,
  publicDir: false,
  logLevel: 'warn',
  plugins: [writeModule],
  build: {
    write: false,
    // Exported files should open in any current browser, not only in the app's WebView.
    target: 'es2022',
    lib: { entry: join(src, 'entry.ts'), formats: ['iife'], name: 'SlidrRuntime' },
  },
};
